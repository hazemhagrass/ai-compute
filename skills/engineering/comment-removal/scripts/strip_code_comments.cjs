const ts = require("typescript");

const PROTECT = [
  /eslint-(disable|enable)/,
  /@ts-(expect-error|ignore|nocheck|check)/,
  /@vitest-environment/,
  /@jest-environment/,
  /prettier-ignore/,
  /v8 ignore/,
  /istanbul ignore/,
  /c8 ignore/,
  /@__PURE__/,
  /webpackChunkName/,
  /webpackIgnore/,
  /^\s*\/\/\/\s*<reference/,
  /do not edit/i,
  /@generated\b/,
  /code generated by/i,
  /automatically generated/i,
  /this file is auto-?generated/i,
];
const isProtected = (t) => PROTECT.some((re) => re.test(t));
const isJsxFile = (f) => f.endsWith(".tsx") || f.endsWith(".jsx");

const LITERAL_KINDS = new Set([
  ts.SyntaxKind.StringLiteral,
  ts.SyntaxKind.NoSubstitutionTemplateLiteral,
  ts.SyntaxKind.TemplateHead,
  ts.SyntaxKind.TemplateMiddle,
  ts.SyntaxKind.TemplateTail,
  ts.SyntaxKind.RegularExpressionLiteral,
  ts.SyntaxKind.JsxText,
  ts.SyntaxKind.JsxAttributeValue,
]);

function parse(file, text) {
  const jsx = isJsxFile(file);
  const sf = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    false,
    jsx ? ts.ScriptKind.TSX : ts.ScriptKind.TS,
  );
  return sf;
}

function literalRanges(sf) {
  const ranges = [];
  (function visit(n) {
    if (LITERAL_KINDS.has(n.kind)) ranges.push([n.getStart(sf), n.getEnd()]);
    n.forEachChild(visit);
  })(sf);
  return ranges;
}

function collectComments(file, text) {
  const sf = parse(file, text);
  const literals = literalRanges(sf);
  const inLiteral = (p) => literals.some(([a, b]) => p >= a && p < b);
  const comments = [];
  const re = /\/\/|\/\*/g;
  let m;
  while ((m = re.exec(text)) !== null) {
    const pos = m.index;
    if (inLiteral(pos)) continue;
    if (comments.some((c) => pos >= c.pos && pos < c.end)) continue;
    let end;
    if (m[0] === "//") {
      const nl = text.indexOf("\n", pos);
      end = nl === -1 ? text.length : nl;
    } else {
      const close = text.indexOf("*/", pos + 2);
      if (close === -1) continue;
      end = close + 2;
    }
    comments.push({ pos, end, text: text.slice(pos, end) });
  }
  return { sf, comments };
}

function tokens(file, text) {
  const sf = parse(file, text);
  const out = [];
  (function visit(n) {
    if (ts.isToken(n)) {
      if (n.kind === ts.SyntaxKind.JsxText) {
        const norm = n.getText(sf).replace(/\s+/g, " ").trim();
        if (norm !== "") out.push({ kind: n.kind, text: norm, pos: n.getStart(sf) });
        return;
      }
      out.push({ kind: n.kind, text: n.getText(sf), pos: n.getStart(sf) });
      return;
    }
    n.forEachChild(visit);
  })(sf);
  return out;
}

function cutRanges(file, text, comments) {
  const sf = parse(file, text);
  const cuts = [];
  const protectedJsx = [];
  for (const c of comments) if (!isProtected(c.text)) cuts.push({ pos: c.pos, end: c.end });
  (function visit(n, parent) {
    if (ts.isJsxExpression(n) && !n.expression) {
      const t = text.slice(n.getStart(sf), n.getEnd());
      const kids = parent?.children ? [...parent.children] : [];
      const i = kids.indexOf(n);
      const neighbourIsText = [kids[i - 1], kids[i + 1]].some(
        (k) => k && ts.isJsxText(k) && k.getText(sf).trim() !== "",
      );
      if (isProtected(t) || !t.trim().startsWith("{")) {
      } else if (neighbourIsText) {
        protectedJsx.push({ pos: n.getStart(sf), end: n.getEnd(), text: t });
      } else {
        cuts.push({ pos: n.getStart(sf), end: n.getEnd() });
      }
    }
    n.forEachChild((c) => visit(c, n));
  })(sf);
  return { cuts: mergeRanges(cuts), protectedJsx };
}

function mergeRanges(ranges) {
  const out = [];
  for (const r of [...ranges].sort((a, b) => a.pos - b.pos)) {
    const last = out[out.length - 1];
    if (last && r.pos <= last.end) last.end = Math.max(last.end, r.end);
    else out.push({ pos: r.pos, end: r.end });
  }
  return out;
}

const lineOf = (text, p) => text.slice(0, p).split("\n").length;

function strip(file, text) {
  const { comments } = collectComments(file, text);
  const kept = comments.filter((c) => isProtected(c.text)).map((c) => c.text.split("\n")[0].trim());
  const { cuts, protectedJsx } = cutRanges(file, text, comments);
  if (cuts.length === 0) return { text, removed: 0, kept, ok: true, cuts, comments, protectedJsx };

  const lines = text.split("\n");
  const out = [];
  let removed = 0;
  let offset = 0;
  for (const line of lines) {
    const ls = offset;
    const le = offset + line.length;
    offset = le + 1;
    if (!cuts.some((c) => c.pos < le && c.end > ls)) {
      out.push(line);
      continue;
    }
    let pieces = "";
    let cursor = ls;
    for (const c of cuts) {
      if (c.end <= ls || c.pos >= le) continue;
      const s = Math.max(c.pos, ls);
      const e = Math.min(c.end, le);
      if (s > cursor) pieces += text.slice(cursor, s);
      cursor = e;
    }
    pieces += text.slice(cursor, le);
    const stripped = pieces.trimEnd();
    if (stripped.trim() === "") {
      if (line.trim() !== "") removed += 1;
      continue;
    }
    out.push(stripped);
  }

  let result = out
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .replace(/^\n+/, "");
  if (!result.endsWith("\n")) result += "\n";

  const before = tokens(file, text).filter((t) => !cuts.some((c) => t.pos >= c.pos && t.pos < c.end));
  const after = tokens(file, result);
  const ok =
    before.length === after.length && before.every((t, i) => t.kind === after[i].kind && t.text === after[i].text);
  let divergence = null;
  if (!ok) {
    for (let i = 0; i < Math.max(before.length, after.length); i++) {
      if (!before[i] || !after[i] || before[i].kind !== after[i].kind || before[i].text !== after[i].text) {
        const show = (t) => (t ? `${ts.SyntaxKind[t.kind]} ${JSON.stringify(t.text.slice(0, 40))} @line ${lineOf(text, t.pos)}` : "none");
        divergence = { i, before: show(before[i]), after: show(after[i]), line: lineOf(text, (before[i] ?? after[i]).pos) };
        break;
      }
    }
  }
  return { text: result, removed, kept, ok, cuts, comments, protectedJsx, divergence };
}

module.exports = { collectComments, cutRanges, isProtected, strip, tokens, parse, mergeRanges };
